-- unrealUI :: core/auradata.lua
--
-- Base durations for named auras, and the adjustments that make a handful of
-- them depend on the player rather than on the spell alone. This file is data
-- plus one lookup; the tracking that turns a duration into a running timer
-- lives in modules/auras.lua.
--
-- ---------------------------------------------------------------------------
-- Why a table exists at all
-- ---------------------------------------------------------------------------
--
-- knowledge.json / auras.no_native_debuff_expiry_time (SUPPORTED,
-- BEHAVIOR_VERIFIED, RUNTIME_MEASURED): a target aura's remaining time cannot
-- be read from this client. UnitDebuff returns (texture, count, debuffType)
-- and nothing more, and GameTooltip:SetUnitDebuff produces exactly two lines --
-- the name and a static description -- with no timer anywhere in it, measured
-- against a live warlock Immolate. The client's only remaining-time API,
-- GetPlayerBuffTimeLeft, is indexed by GetPlayerBuff and covers the player's
-- own auras only; there is no target equivalent.
--
-- That record's own solution text says a target timer "would require
-- reproducing pfUI's whole duration-table + combat-log-timestamp
-- reconstruction ... which is out of scope unless explicitly requested". It
-- was explicitly requested, so this is that reconstruction -- kept to the
-- smallest shape that answers it.
--
-- The durations come from UnrealPfUI's libs/libdebuff.lua duration table
-- (env/locales_enUS.lua, DBC-extracted), which is WORKING_SOURCE evidence per
-- .claude/rules/unreal-pfui.md: a working implementation on this same client,
-- not runtime verification. Only the data is taken. pfUI's library framework,
-- its combat-log parsers, its pending-spell machinery and its cast hooks are
-- not reproduced -- modules/auras.lua stamps an aura when it first observes it,
-- which needs none of them.
--
-- ---------------------------------------------------------------------------
-- What this means for accuracy
-- ---------------------------------------------------------------------------
--
--   * A duration here is the spell's full duration at max rank. Rank is not
--     recoverable for another unit's aura, and pfUI's own display path passes
--     rank as nil for the same reason (libdebuff:UnitDebuff, "no backport"),
--     so a low-rank aura reads long.
--   * The table is debuff-weighted because that is what pfUI's extractor
--     produced. Many buffs are absent; an aura with no entry here simply gets
--     no timer and no wipe, which is the honest result rather than a guess.
--   * Nothing here is verified against this server's own spell data. If
--     Emberveil retuned a duration, this table is wrong for that spell and the
--     timer restarts when the aura outlives it -- see RestampExpired in
--     modules/auras.lua.
--
-- ---------------------------------------------------------------------------
-- Local budget
-- ---------------------------------------------------------------------------
--
-- rules/unreal-ui.md caps a file's main chunk at 200 top-level locals and a
-- file that overruns it fails to load in silence. The 900-plus entries below
-- are one table on one local, which is the table form that rule prescribes.

