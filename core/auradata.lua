-- ---------------------------------------------------------------------------
-- Player-dependent adjustments
--
-- A few durations are not a property of the spell alone. pfUI applies these
-- from libdebuff:GetDuration; they are ported with one addition -- each is
-- gated on the player's class. pfUI reads the talent position blind, and two
-- of these positions collide across classes (warrior 2/1 Booming Voice and
-- rogue 2/1 Improved Gouge), so an ungated read gives a rogue watching a
-- warrior mob's Demoralizing Shout the wrong number.
--
-- The gate is a narrowing, not a fix: the talent bonus only applies when the
-- player cast the aura, and no caster is recoverable for a target aura on this
-- client (auras.no_native_debuff_expiry_time). A warrior watching another
-- warrior's Demoralizing Shout still gets their own Booming Voice rank applied
-- to it. That is the same limit pfUI carries.
-- ---------------------------------------------------------------------------
local function Call(name, a, b)
  local fn = U.G(name)
  if type(fn) ~= "function" then return nil end
  local ok, v1, v2, v3, v4, v5 = pcall(fn, a, b)
  if not ok then return nil end
  return v1, v2, v3, v4, v5
end

local function PlayerClass()
  local _, class = Call("UnitClass", "player")
  return type(class) == "string" and class or nil
end

local function ComboPoints()
  return tonumber(Call("GetComboPoints")) or 0
end

-- GetTalentInfo's fifth return is the number of points spent.
local function TalentRank(tab, index)
  local _, _, _, _, count = Call("GetTalentInfo", tab, index)
  return tonumber(count) or 0
end

local function Adjust(name, duration)
  local class = PlayerClass()

  if name == "Rupture" and class == "ROGUE" then
    return duration + ComboPoints() * 2
  elseif name == "Kidney Shot" and class == "ROGUE" then
    return duration + ComboPoints()
  elseif name == "Gouge" and class == "ROGUE" then
    return duration + TalentRank(2, 1) * 0.5
  elseif name == "Demoralizing Shout" and class == "WARRIOR" then
    -- Booming Voice: +10% of the base per point.
    return duration + duration / 100 * (TalentRank(2, 1) * 10)
  elseif name == "Shadow Word: Pain" and class == "PRIEST" then
    return duration + TalentRank(3, 4) * 3
  elseif name == "Frostbolt" and class == "MAGE" then
    -- Permafrost: +1s per point.
    return duration + TalentRank(3, 7)
  end

  return duration
end

-- Seconds this aura should run for, or nil when the table has no entry --
-- which is the signal modules/auras.lua uses to draw no timer at all rather
-- than to invent one.
function U.AuraDuration(name)
  if type(name) ~= "string" or name == "" then return nil end

  local base = DURATION[name]
  if not base or base <= 0 then return nil end

  local adjusted = Adjust(name, base)
  if type(adjusted) ~= "number" or adjusted <= 0 then return base end
  return adjusted
end

-- How much the table actually covers, reported through U.AuraStats so
-- "/uui perf" can answer "why does this aura have no timer" with a number.
-- Counted once at load rather than per read: the walk is 900-odd keys and the
-- answer never changes.
local count = 0
local _
for _ in pairs(DURATION) do count = count + 1 end

function U.AuraDurationCount()
  return count
end
