"""Builds Database/unit_reactions.lua: every creature's base reaction to each
playable race, from the VMaNGOS world database.

The client gives a nameplate no reaction signal (no GetStatusBarColor, no
unit token, a white name), so modules/nameplates.lua colours a plate it has
not seen targeted or moused over from this table.

Reaction follows VMaNGOS FactionTemplateEntry::IsHostileTo / IsFriendlyTo,
checked both ways, between the creature's faction template and the race's
player template: hostile wins, then friendly, otherwise neutral. Reputation is
not modelled (a faction the player is at war with, or exalted with, keeps its
base reaction here); unrealUI's live target/mouseover reading overrides it.

Rows: per creature entry the highest patch <= PATCH; per faction template the
highest build. Only non-hostile entries are written, a missing id reads as
hostile. A value is one letter (H/N/F) when every race agrees, otherwise eight
letters in UnitRace's numeric order: Human, Orc, Dwarf, NightElf, Scourge,
Tauren, Gnome, Troll.

Usage: python -B tools/import_unit_reactions.py [path/to/mangos.sqlite]
"""
from pathlib import Path
import sqlite3
import sys

DEFAULT_DB = Path(r'C:\Games\Azeroth Launcher\runtime-reports'
                  r'\unrealconquest-poi-review\vendor\Vmangos-DB\mangos.sqlite')
OUT = Path(__file__).resolve().parent.parent / 'Database' / 'unit_reactions.lua'
PATCH = 10
# UnitRace's third return order -> the race's player faction template.
RACE_TEMPLATES = [1, 2, 3, 4, 5, 6, 115, 116]


def load(db):
    c = sqlite3.connect('file:%s?mode=ro' % db.as_posix(), uri=True)
    templates = {}
    for row in c.execute(
            'select id, faction_id, our_mask, friendly_mask, hostile_mask, '
            'enemy_faction1, enemy_faction2, enemy_faction3, enemy_faction4, '
            'friend_faction1, friend_faction2, friend_faction3, friend_faction4 '
            'from faction_template order by build'):
        templates[row[0]] = {
            'faction': row[1], 'our': row[2], 'friendly': row[3],
            'hostile': row[4], 'enemies': row[5:9], 'friends': row[9:13],
        }
    creatures = {}
    for entry, faction in c.execute(
            'select entry, faction from creature_template where patch <= ? '
            'order by patch', (PATCH,)):
        creatures[entry] = faction
    revision = None
    try:
        revision = c.execute('select * from migrations order by 1 desc limit 1').fetchone()
    except sqlite3.Error:
        pass
    return templates, creatures, revision


def hostile_to(a, b):
    if b['faction']:
        if b['faction'] in a['enemies']:
            return True
        if b['faction'] in a['friends']:
            return False
    return (a['hostile'] & b['our']) != 0


def friendly_to(a, b):
    if b['faction']:
        if b['faction'] in a['enemies']:
            return False
        if b['faction'] in a['friends']:
            return True
    return (a['friendly'] & b['our']) != 0 or (a['our'] & b['friendly']) != 0


def reaction(creature, player):
    if hostile_to(creature, player) or hostile_to(player, creature):
        return 'H'
    if friendly_to(creature, player):
        return 'F'
    return 'N'


def main():
    db = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB
    templates, creatures, revision = load(db)
    players = [templates[t] for t in RACE_TEMPLATES]
    out = {}
    unknown = 0
    for entry in sorted(creatures):
        tpl = templates.get(creatures[entry])
        if not tpl:
            unknown += 1
            continue
        letters = ''.join(reaction(tpl, p) for p in players)
        if letters == 'H' * 8:
            continue
        out[entry] = letters[0] if letters == letters[0] * 8 else letters

    lines = [
        '-- unrealUI :: Database/unit_reactions.lua',
        '-- GENERATED by tools/import_unit_reactions.py -- do not edit by hand.',
        '-- Creature id -> base reaction (H/N/F) to the player, one letter for',
        '-- every race or eight in UnitRace order (Human, Orc, Dwarf, NightElf,',
        '-- Scourge, Tauren, Gnome, Troll). Absent ids are hostile. Source:',
        '-- VMaNGOS world database, creature_template patch <= %d, '
        'faction_template.' % PATCH,
        '',
        'local U = UnrealUI',
        '',
        'U.unitReactions = {',
        '  ["patch"] = %d,' % PATCH,
        '  ["byId"] = {',
    ]
    for entry, value in sorted(out.items()):
        lines.append('    [%d] = "%s",' % (entry, value))
    lines += ['  },', '}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('creatures %d, written %d non-hostile, unknown template %d, revision %s'
          % (len(creatures), len(out), unknown, revision))
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
